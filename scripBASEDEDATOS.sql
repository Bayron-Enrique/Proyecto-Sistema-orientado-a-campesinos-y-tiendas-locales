  CREATE OR REPLACE NONEDITIONABLE PROCEDURE "INVENTARIOS"."SP_ATENDER_ALERTA" (
    p_id_alerta IN NUMBER,
    p_id_usuario IN NUMBER
)
IS
BEGIN

    UPDATE ALERTAS
    SET ESTADO_ALERTA = 'atendida',
        ATENDIDA_POR = p_id_usuario,
