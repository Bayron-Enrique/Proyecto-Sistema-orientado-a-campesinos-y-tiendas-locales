--  DDL for Trigger TRG_GENERAR_ALERTA
--------------------------------------------------------

  CREATE OR REPLACE NONEDITIONABLE TRIGGER "INVENTARIOS"."TRG_GENERAR_ALERTA" 
AFTER UPDATE OF STOCK_ACTUAL ON PRODUCTOS
FOR EACH ROW
DECLARE
    V_EXISTE NUMBER;
BEGIN

    IF :NEW.STOCK_ACTUAL <= :NEW.STOCK_MINIMO
       AND :NEW.ESTADO = 'activo' THEN

        SELECT COUNT(*)
        INTO V_EXISTE
        FROM ALERTAS
        WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
          AND ESTADO_ALERTA = 'pendiente';

        IF V_EXISTE = 0 THEN

            INSERT INTO ALERTAS(
                ID_ALERTA,
                ID_PRODUCTO,
                FECHA_ALERTA,
                STOCK_AL_MOMENTO,
                ESTADO_ALERTA,
                ACTIVO,
                FECHA_CREACION
            )
            VALUES(
                SEQ_ALERTAS.NEXTVAL,
                :NEW.ID_PRODUCTO,
                SYSDATE,
                :NEW.STOCK_ACTUAL,
                'pendiente',
                1,
                SYSDATE
            );

        END IF;

    END IF;

END;

